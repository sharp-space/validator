using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Sharp.Validator.SourceGenerator.Generation;

/// <summary>Emits a <c>[ModuleInitializer]</c> that seeds the precompiled accessors (flat, null-safe, elements) into the registry.</summary>
internal static partial class Emitter
{
    public static void EmitAccessors(SourceProductionContext context, ImmutableArray<AccessorInfo> accessors)
    {
        if (accessors.IsEmpty) return;

        var distinct = accessors
            .Distinct()
            .OrderBy(static x => x.Kind)
            .ThenBy(static x => x.ModelFqn, StringComparer.Ordinal)
            .ThenBy(static x => x.PropertyFqn, StringComparer.Ordinal)
            .ThenBy(static x => x.Path, StringComparer.Ordinal)
            .ToList();

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");

        // The accessor lambdas return the member's declared type into Func<…, TProperty>; a nullable-reference mismatch
        // (e.g. string? member, string TProperty after annotation erasure) is harmless at runtime, so the file opts out
        // of nullable analysis rather than threading annotations through the generic arguments.
        builder.AppendLine("#nullable disable");
        builder.AppendLine("#pragma warning disable CS1591");
        AppendExperimentalPragma(builder, distinct.Select(static accessor => accessor.ExperimentalIds));
        builder.AppendLine("namespace Sharp.Validator.Generated");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>Source-generated, NativeAOT-fast property accessors for this assembly.</summary>");
        AppendGeneratedCodeAttributes(builder, "    ");
        builder.AppendLine("    file static class GeneratedAccessorRegistrar");
        builder.AppendLine("    {");
        builder.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("        internal static void Initialize()");
        builder.AppendLine("        {");
        foreach (var accessor in distinct)
            AppendRegistration(builder, accessor);

        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        context.AddSource("SharpValidator.Accessors.g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
    }

    // Reserved keywords are escaped at emission only (m.@event); the registry key keeps the raw member name so it stays
    // aligned with the runtime's member.Name-derived paths.
    private static string Identifier(string name) =>
        SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;

    private static void AppendRegistration(StringBuilder builder, AccessorInfo accessor)
    {
        var chain = accessor.Chain.AsImmutableArray();
        var model = accessor.ModelFqn;
        var property = accessor.PropertyFqn;
        var key = $"<{model}, {property}>(\"{accessor.Path}\", static ({model} m) =>";
        switch (accessor.Kind)
        {
            case AccessorKind.Property:
                builder.AppendLine(
                    $"            global::Sharp.Validator.Bindings.AccessorRegistry.RegisterProperty{key} m.{Identifier(chain[0].Member)});");

                break;

            case AccessorKind.NullSafe:
                builder.AppendLine($"            global::Sharp.Validator.Bindings.AccessorRegistry.RegisterNullSafe{key}");
                builder.AppendLine("            {");
                AppendIntermediates(builder, chain, "return (false, default);");
                builder.AppendLine($"                return (true, {Leaf(chain)});");
                builder.AppendLine("            });");
                break;

            case AccessorKind.Elements:
                var enumerable = $"global::System.Collections.Generic.IEnumerable<{property}>";
                if (chain.Length == 1)
                {
                    builder.AppendLine(
                        $"            global::Sharp.Validator.Bindings.AccessorRegistry.RegisterElements{key} ({enumerable})m.{Identifier(chain[0].Member)});");
                }
                else
                {
                    builder.AppendLine($"            global::Sharp.Validator.Bindings.AccessorRegistry.RegisterElements{key}");
                    builder.AppendLine("            {");
                    AppendIntermediates(builder, chain, "return null;");
                    builder.AppendLine($"                return ({enumerable})({Leaf(chain)});");
                    builder.AppendLine("            });");
                }

                break;
        }
    }

    // Dereferences each intermediate into a local, returning early (via returnOnNull) when a guarded one is null.
    private static void AppendIntermediates(StringBuilder builder, ImmutableArray<AccessorStep> chain, string returnOnNull)
    {
        for (var index = 0; index < chain.Length - 1; index++)
        {
            var source = index == 0 ? "m" : "t" + (index - 1);
            builder.AppendLine($"                var t{index} = {source}.{Identifier(chain[index].Member)};");
            if (chain[index].Guard)
                builder.AppendLine($"                if (t{index} is null) {returnOnNull}");
        }
    }

    // The leaf is read off the last intermediate local (or the parameter for a single-hop chain).
    private static string Leaf(ImmutableArray<AccessorStep> chain)
    {
        var source = chain.Length == 1 ? "m" : "t" + (chain.Length - 2);
        return $"{source}.{Identifier(chain[chain.Length - 1].Member)}";
    }
}