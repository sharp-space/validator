using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Sharp.Validator.SourceGenerator.Analyzers;

namespace Sharp.Validator.SourceGenerator.Generation;

/// <summary>
/// Emits the AOT-safe DI registrar into the consumer assembly. Inaccessible validators are skipped here; <see cref="InaccessibleValidatorAnalyzer" />
/// reports them as SVL001 at their declaration site.
/// </summary>
internal static partial class Emitter
{
    public static void EmitValidators(SourceProductionContext context, ImmutableArray<ValidatorInfo> validators)
    {
        // The registrar is emitted even when there is nothing to register: under Native AOT, AddValidators(assembly)
        // throws for an assembly without one, taking it for an assembly built without the generator.

        // One registration per validator type (a partial type is discovered once per declaration), listing every
        // interface it is registered as. Ordered by implementation, so the validators for one interface keep the
        // ordinal order they had when each interface was registered on its own.
        var accessible = validators
            .Where(static x => x.Accessible)
            .Distinct()
            .GroupBy(static x => x.ImplementationFqn, StringComparer.Ordinal)
            .OrderBy(static x => x.Key, StringComparer.Ordinal)
            .ToList();

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable CS1591");

        AppendExperimentalPragma(builder,
            accessible.SelectMany(static group => group).Select(static validator => validator.ExperimentalIds));

        builder.AppendLine("namespace Sharp.Validator.Generated");
        builder.AppendLine("{");
        builder.AppendLine("    using global::Microsoft.Extensions.DependencyInjection;");
        builder.AppendLine();
        builder.AppendLine("    /// <summary>Source-generated, NativeAOT-safe validator registrations for this assembly.</summary>");
        AppendGeneratedCodeAttributes(builder, "    ");

        // file-local: every assembly emits this name, and a project that sees another's internals through
        // InternalsVisibleTo would otherwise get CS0436 from generated code.
        builder.AppendLine("    file static class GeneratedValidatorRegistrar");
        builder.AppendLine("    {");
        builder.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("        internal static void Initialize() =>");
        builder.AppendLine(
            "            global::Sharp.Validator.Bindings.ValidatorRegistry.AddRegistrar(typeof(GeneratedValidatorRegistrar).Assembly, Register);");

        builder.AppendLine();
        builder.AppendLine(
            "        private static void Register(IServiceCollection services, global::System.Func<global::System.Type, ServiceLifetime> lifetime, global::Sharp.Validator.ValidatorBuilderOptions? defaults)");

        builder.AppendLine("        {");
        foreach (var validator in accessible)
        {
            var serviceTypes = string.Join(", ", validator
                .Select(static x => x.ServiceInterfaceFqn)
                .OrderBy(static x => x, StringComparer.Ordinal)
                .Select(static x => $"typeof({x})"));

            builder.AppendLine(
                $"            global::Sharp.Validator.Bindings.ValidatorRegistry.Register(services, typeof({validator.Key}), " +
                $"lifetime(typeof({validator.Key})), defaults, {serviceTypes});");
        }

        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        context.AddSource("SharpValidator.Registrations.g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
    }
}